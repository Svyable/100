def library_href(site, page, rel_path, fragment=""):
    for d in site.library:
        if d["rel"] == rel_path:
            return rel(page, d["path"]) + (("#" + fragment) if fragment else "")
    return None


def dossier_link(site, page, path, label="Read the dossier"):
    if not path:
        return ""
    href = library_href(site, page, path)
    if href:
        return f'<a class="text-link" href="{href}">{E(label)} <span aria-hidden="true">→</span></a>'
    return repo_link(path, label, "text-link")


