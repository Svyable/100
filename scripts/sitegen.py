class Site:
    """All validated data plus cross-indexes, computed once."""

    def __init__(self, portfolio):
        items, program, solved = load()
        self.portfolio = portfolio
        self.dispatch = {p["id"]: p for p in portfolio["problems"]}
        self.approach = portfolio["approach"]
        self.mines = portfolio["mines"]["mines"]
        self.roadmap_doc = portfolio["roadmap"]
        self.work = workqueue.snapshot()
        self.work_by_problem = defaultdict(list)
        for w in self.work["items"]:
            for pid in w["problems"]:
                self.work_by_problem[pid].append(w)
        self.items = items
        self.program = program
        self.solved = solved
        self.execution = execution_order(items, program)
        baseline = sorted(items, key=lambda p: (-score(p), p["id"]))
        self.rank = {p["id"]: i for i, p in enumerate(baseline, 1)}
        self.by_id = {p["id"]: p for p in items}
        self.ordered = sorted(items, key=lambda p: self.dispatch[p["id"]]["dispatch_rank"])
        self.campaign = {c["problem_id"]: c for c in program["campaigns"] if c["problem_id"] in self.by_id}
        self.milestones = defaultdict(list)
        for m in program["milestones"]:
            self.milestones[m["problem_id"]].append(m)
        self.lab = lab.snapshot()
        self.covered = set(self.lab["covered_problems"])
        self.probes = defaultdict(list)
        for probe in self.lab["probes"]:
            self.probes[probe["problem_id"]].append(probe)
        self.engines = {e["id"]: e for e in self.lab["engines"]}
        self.roadmap = {r["problem_id"]: r for r in self.lab["roadmap"]}
        self.claims_doc = json.loads((ROOT / "data" / "claim_reviews_2026.json").read_text(encoding="utf-8"))
        self.claims = {r["id"]: r for r in self.claims_doc["reviews"]}
        self.external = defaultdict(list)
        for x in json.loads((ROOT / "data" / "external_claims.json").read_text(encoding="utf-8")):
            self.external[x["problem_id"]].append(x)
        self.lean_targets = json.loads((ROOT / "data" / "lean_targets.json").read_text(encoding="utf-8"))
        self.formal_doc = json.loads((ROOT / "data" / "formalization.json").read_text(encoding="utf-8"))
        self.formal = {e["problem_id"]: e for e in self.formal_doc["entries"] if e["problem_id"] in self.by_id}
        self.lean_src = {e["module"]: (ROOT / e["module"]).read_text(encoding="utf-8") for e in self.formal.values()}
        self.fields = sorted({p["field"] for p in items})
        self.field_slug = {f: slug(f) for f in self.fields}
        self.library = discover_library()
        self.backlinks = defaultdict(list)
        for doc in self.library:
            for pid in sorted(set(re.findall(r"\bM\d{3}\b", doc["source"]))):
                if pid in self.by_id:
                    self.backlinks[pid].append(doc)
        dates = [p["checked_on"] for p in items if p["checked_on"]]
        dates += [program["as_of"], self.claims_doc["reviewed_on"]]
        dates += [m["verified_on"] for m in program["milestones"] if m.get("verified_on")]
        self.updated = max(dates)

    def rec(self, pid):
        return dict(self.dispatch[pid])

    def drank(self, pid):
        """Dispatch rank: the default order everywhere (what to do next)."""
        return self.dispatch[pid]["dispatch_rank"]

    def problem_path(self, pid):
        return f"problems/{pid}/"

    def readiness_parts(self, pid):
        c = self.campaign.get(pid)
        if not c:
            return []
        marks = self.milestones.get(pid, [])
        parts = [("Formal campaign brief", 2, True),
                 ("Runnable independent verifier", 3, bool(c["verifier"])),
                 ("Reproduced known benchmark", 2, any(m["classification"] == "reproduced_known" for m in marks)),
                 ("Independently reviewed restricted theorem", 3,
                  any(m["classification"] == "restricted_verified" for m in marks))]
        return parts


def discover_library():
    """Every Markdown research document worth publishing, with a stable slug."""
    sources = sorted(ROOT.glob("*.md")) + sorted((ROOT / "research").glob("*.md")) + \
        sorted((ROOT / "docs").glob("*.md")) + [ROOT / "lean" / "README.md"]
    docs = []
    for path in sources:
        rel = path.relative_to(ROOT).as_posix()
        if rel in ("README.md", "CLAUDE.md") or not path.is_file():
            continue
        text = path.read_text(encoding="utf-8")
        heads = mdlite.headings(text)
        title = next((h[1] for h in heads if h[0] == 1), path.stem.replace("_", " ").title())
        title = re.sub(r"[`*]", "", title)
        group = "Research dossiers" if rel.startswith("research/") else \
            "Method & governance" if rel.startswith(("docs/", "lean/")) or rel in ("CONTRIBUTING.md", "AGENTS.md", "LEAN.md") else "Generated reports"
        stem_slug = slug(path.stem) if path.stem.upper() != "README" else slug(rel.rsplit(".", 1)[0])
        docs.append({"rel": rel, "slug": stem_slug, "title": title, "source": text,
                     "group": group, "path": f"library/{stem_slug}/"})
    seen = Counter(d["slug"] for d in docs)
    for d in docs:
        if seen[d["slug"]] > 1:
            d["slug"] = slug(d["rel"].rsplit(".", 1)[0])
            d["path"] = f"library/{d['slug']}/"
    return docs


