def scatter_svg(site, page):
    """Impact × attackability; every problem is a dot linking to its page."""
    cell, pad_l, pad_b, pad_t = 116, 64, 54, 16
    w, h = pad_l + cell * 5 + 16, pad_t + cell * 5 + pad_b
    cells = defaultdict(list)
    for p in site.ordered:
        cells[(p["attackability"], p["impact"])].append(p)
    out = [f'<svg class="chart scatter" viewBox="0 0 {w} {h}" role="img" aria-labelledby="scatter-title scatter-desc">',
           '<title id="scatter-title">Impact versus attackability for all 100 problems</title>',
           '<desc id="scatter-desc">Each dot is one problem, placed in the cell for its attackability (horizontal, 1 to 5) and impact (vertical, 1 to 5) scores, coloured by evidence state. A ring marks problems with an exact verifier. A table view follows.</desc>']
    for k in range(6):
        x = pad_l + k * cell
        y = pad_t + k * cell
        out.append(f'<line class="grid" x1="{x}" y1="{pad_t}" x2="{x}" y2="{pad_t + 5 * cell}"/>')
        out.append(f'<line class="grid" x1="{pad_l}" y1="{y}" x2="{pad_l + 5 * cell}" y2="{y}"/>')
    for k in range(1, 6):
        out.append(f'<text class="tick" x="{pad_l + (k - .5) * cell}" y="{pad_t + 5 * cell + 20}" text-anchor="middle">{k}</text>')
        out.append(f'<text class="tick" x="{pad_l - 12}" y="{pad_t + (5 - k + .5) * cell + 4}" text-anchor="end">{k}</text>')
    out.append(f'<text class="axis-label" x="{pad_l + 2.5 * cell}" y="{h - 8}" text-anchor="middle">Attackability →</text>')
    out.append(f'<text class="axis-label" transform="translate(16 {pad_t + 2.5 * cell}) rotate(-90)" text-anchor="middle">Impact →</text>')
    for (a, i), ps in sorted(cells.items()):
        x0 = pad_l + (a - 1) * cell
        y0 = pad_t + (5 - i) * cell
        per_row = 6 if len(ps) <= 24 else 8 if len(ps) <= 48 else 10
        step = (cell - 16) / per_row
        radius = min(5.5, step / 2 - 1)
        out.append(f'<text class="cell-count" x="{x0 + cell - 6}" y="{y0 + 13}" text-anchor="end">{len(ps)}</text>')
        for k, p in enumerate(ps):
            cx = x0 + 10 + step * (k % per_row) + step / 2
            cy = y0 + 22 + step * (k // per_row) + step / 2
            ring = ' class="dot verified"' if p["id"] in site.covered else ' class="dot"'
            out.append(f'<a href="{rel(page, site.problem_path(p["id"]))}" aria-label="{E(p["id"] + " " + p["name"])}">'
                       f'<circle{ring} data-series="{SERIES[p["evidence_state"]]}" cx="{cx:.1f}" cy="{cy:.1f}" r="{radius:.1f}">'
                       f'<title>{E(p["id"])} · {E(p["name"])} — impact {i}, attackability {a}, {E(EVIDENCE[p["evidence_state"]])}</title></circle></a>')
    out.append("</svg>")
    return "".join(out)


def ladder_svg(site, page, n=30):
    """Top-n execution order: editorial score bar plus readiness segment."""
    row, pad_l, w = 22, 270, 860
    h = row * n + 34
    scale = (w - pad_l - 60) / 110
    out = [f'<svg class="chart ladder" viewBox="0 0 {w} {h}" role="img" aria-labelledby="ladder-title">',
           f'<title id="ladder-title">Readiness ladder: the top {n} problems by execution index, split into editorial score and readiness bonus</title>']
    for t in (0, 25, 50, 75, 100):
        x = pad_l + t * scale
        out.append(f'<line class="grid" x1="{x:.1f}" y1="0" x2="{x:.1f}" y2="{row * n}"/>'
                   f'<text class="tick" x="{x:.1f}" y="{row * n + 16}" text-anchor="middle">{t}</text>')
    by_execution = sorted(site.items, key=lambda q: site.execution[q["id"]]["execution_rank"])
    for k, p in enumerate(by_execution[:n]):
        y = k * row
        ex = site.execution[p["id"]]
        sc = score(p)
        label = f'{ex["execution_rank"]}. {p["name"]}'
        if len(label) > 40:
            label = label[:39] + "…"
        out.append(f'<a href="{rel(page, site.problem_path(p["id"]))}"><g class="bar-row">'
                   f'<title>{E(p["id"])} · {E(p["name"])} — editorial {sc} + readiness {ex["readiness"]} = {ex["execution_score"]}</title>'
                   f'<rect class="hit" x="0" y="{y}" width="{w}" height="{row}"/>'
                   f'<text class="bar-label" x="{pad_l - 10}" y="{y + 15}" text-anchor="end">{E(label)}</text>'
                   f'<rect class="bar-base" x="{pad_l}" y="{y + 5}" width="{sc * scale:.1f}" height="12" rx="2"/>')
        if ex["readiness"]:
            out.append(f'<rect class="bar-ready" x="{pad_l + sc * scale + 2:.1f}" y="{y + 5}" width="{max(0, ex["readiness"] * scale - 2):.1f}" height="12" rx="2"/>')
        out.append(f'<text class="bar-value" x="{pad_l + ex["execution_score"] * scale + 6:.1f}" y="{y + 15}">{ex["execution_score"]}</text></g></a>')
    out.append(f'<text class="tick" x="{pad_l + 55 * scale:.1f}" y="{h - 2}" text-anchor="middle">Execution index</text></svg>')
    return "".join(out)


