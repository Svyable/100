E = html.escape


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def fmt_date(value):
    return value or "not yet recorded"


def https(url):
    return url if isinstance(url, str) and url.startswith("https://") else None


def ext(url, label, cls=""):
    url = https(url)
    if not url:
        return E(label)
    c = f' class="{cls}"' if cls else ""
    return f'<a{c} href="{E(url)}" rel="noopener noreferrer">{E(label)} <span aria-hidden="true">↗</span></a>'


def repo_link(path, label=None, cls=""):
    if not isinstance(path, str) or not re.fullmatch(r"[A-Za-z0-9_./-]+", path) or ".." in path.split("/"):
        return E(label or str(path))
    return ext(BLOB + path, label or path, cls)


LEAN_KEYWORDS = {"def", "abbrev", "theorem", "lemma", "example", "instance", "namespace", "end", "open",
                 "import", "by", "fun", "match", "with", "if", "then", "else", "have", "intro", "exact",
                 "cases", "decide", "unfold", "Prop", "Nat", "Int", "Bool", "true", "false"}
_LEAN_TOKEN = re.compile(r"(/-.*?-/|--[^\n]*|\b[A-Za-z_][A-Za-z0-9_.']*\b|∀|∃|→|↔|¬|∧|∨|≤|≥|≠|:=)", re.S)


def highlight_lean(src):
    """Minimal, escaping-first Lean highlighter (comments, keywords, logical symbols)."""
    out, pos = [], 0
    for m in _LEAN_TOKEN.finditer(src):
        out.append(E(src[pos:m.start()]))
        tok = m.group(0)
        if tok.startswith(("/-", "--")):
            out.append(f'<span class="tk-c">{E(tok)}</span>')
        elif tok in LEAN_KEYWORDS:
            out.append(f'<span class="tk-k">{E(tok)}</span>')
        elif tok in ("∀", "∃", "→", "↔", "¬", "∧", "∨", "≤", "≥", "≠", ":="):
            out.append(f'<span class="tk-o">{E(tok)}</span>')
        else:
            out.append(E(tok))
        pos = m.end()
    out.append(E(src[pos:]))
    return "".join(out)


def lean_decl_block(src, name):
    """The doc comment plus declaration of ``name`` (up to the next blank line)."""
    lines = src.split("\n")
    for k, line in enumerate(lines):
        if re.match(rf"(abbrev|def|theorem)\s+{re.escape(name)}\b", line):
            start = k
            while start > 0 and lines[start - 1].strip() and not lines[start - 1].startswith(("def ", "abbrev ", "theorem ")):
                start -= 1
            end = k
            while end + 1 < len(lines) and lines[end + 1].strip():
                end += 1
            return "\n".join(lines[start:end + 1])
    return ""


