def md_resolver(site, doc, page):
    base = doc["rel"].rsplit("/", 1)[0] if "/" in doc["rel"] else ""
    library = {d["rel"]: d for d in site.library}

    def resolve(href):
        if href.startswith(("http://", "https://")):
            return href
        if href.startswith("#"):
            return href
        if href.startswith(("mailto:", "javascript:", "data:")):
            return None
        path, _, frag = href.partition("#")
        parts = []
        for seg in ((base + "/" + path) if base else path).split("/"):
            if seg in ("", "."):
                continue
            if seg == "..":
                if parts:
                    parts.pop()
                continue
            parts.append(seg)
        target = "/".join(parts)
        if target in library:
            return rel(page, library[target]["path"]) + (("#" + frag) if frag else "")
        if target == "README.md":
            return REPO + ("#" + frag if frag else "")
        if target.startswith("docs/") and target.endswith(".html"):
            return rel(page, target[len("docs/"):])
        return BLOB + target + (("#" + frag) if frag else "")
    return resolve


def render_library_doc(site, doc):
    s = site
    page = doc["path"] + "index.html"
    content = mdlite.render(doc["source"], md_resolver(s, doc, page), drop_first_h1=True)
    heads = [(lvl, text) for lvl, text, _ in mdlite.headings(doc["source"]) if lvl in (2, 3)]
    # Recompute unique ids exactly as the renderer does.
    ids = re.findall(r'<h([23]) id="([^"]+)">', content)
    toc = "".join(
        f'<li class="toc-l{lvl}"><a href="#{E(hid)}">{E(re.sub(r"[`*]", "", text))}</a></li>'
        for (lvl, hid), (_, text) in zip(ids, heads))
    mentioned = sorted(set(re.findall(r"\bM\d{3}\b", doc["source"])) & set(s.by_id), key=lambda q: s.drank(q))
    body = f"""<div class="doc-layout">
<aside class="doc-side">{('<nav class="toc"><span class="detail-label">CONTENTS</span><ol>' + toc + '</ol></nav>') if toc else ''}
{('<div class="doc-mentions"><span class="detail-label">PROBLEMS MENTIONED</span>' + problem_chips(s, page, mentioned) + '</div>') if mentioned else ''}
<p class="muted small">Source: {repo_link(doc['rel'])}</p></aside>
<article class="prose"><p class="eyebrow">{E(doc['group'].upper())}</p><h1>{mdlite._Inline(lambda h: None)(doc['title'])}</h1>
{content}</article></div>"""
    first_para = re.search(r"<p>(.*?)</p>", content, re.S)
    desc = re.sub(r"<[^>]+>", "", first_para.group(1)) if first_para else doc["title"]
    desc = html.unescape(desc)[:240]
    return layout(s, page, doc["title"], desc, body, active="library",
                  crumbs=[("Library", "library/"), (doc["title"], None)])


