#!/usr/bin/env python3
"""Certified structure mines.

    python3 scripts/mine.py                 # run every mine, write the ledger and MINES.md
    python3 scripts/mine.py --mine deck_invariants
    python3 scripts/mine.py --check         # rerun and fail on any drift

A mine records a finite table. The checker recomputes it by a different route.
Nothing here is a theorem, and nothing enters the Solved archive.
"""
import argparse
import json
import sys
import time

import mines
from probes.core import ProbeFailure, digest
from rank import ROOT

FORMAT = "svyable.mines.v1"
RESULTS = ROOT / "data" / "mine_results.json"
REPORT = ROOT / "MINES.md"


class MineError(Exception):
    def __init__(self, code, message):
        super().__init__(message)
        self.code = code


def empty_ledger():
    return {"format": FORMAT, "mines": {}}


def load_ledger():
    if not RESULTS.exists():
        return empty_ledger()
    doc = json.loads(RESULTS.read_text(encoding="utf-8"))
    if doc.get("format") != FORMAT or not isinstance(doc.get("mines"), dict):
        raise MineError(1, "Malformed mine ledger")
    for mine_id, record in doc["mines"].items():
        if mine_id not in mines.MINES or record.get("mine") != mine_id:
            raise MineError(1, f"Ledger entry {mine_id} does not match the mine registry")
    return doc


def dump(doc):
    return json.dumps(doc, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def run_mine(module):
    params = module.MINE["levels"]["smoke"]
    started = time.perf_counter()
    result = module.search(params)
    searched = time.perf_counter()
    try:
        module.check(params, result)
    except ProbeFailure as exc:
        raise MineError(2, f"{module.MINE['id']}: independent check FAILED: {exc}") from exc
    checked = time.perf_counter()
    record = {
        "mine": module.MINE["id"],
        "problem_id": module.MINE["problem_id"],
        "title": module.MINE["title"],
        "engines": module.MINE["engines"],
        "frontier": module.MINE["frontier"],
        "params": params,
        "holds": bool(result["holds"]),
        "scope": module.scope(params),
        "summary": result["summary"],
        "certificate_sha256": digest(result["certificate"]),
    }
    return record, searched - started, checked - searched


def render(ledger):
    present = [mine_id for mine_id in mines.MINES if mine_id in ledger["mines"]]
    lines = [
        "# Structure mines", "",
        "Generated by `python3 scripts/mine.py`. Do not edit by hand.", "",
        "Each table below was recomputed by a second code path. The ranges are inside "
        "published verifications or inside the exhaustive checks already in this repository. "
        "A table is not a theorem and cannot enter the Solved archive.", "",
        "| Mine | Problem | Statement | Certificate |",
        "|---|---|---|---|",
    ]
    for mine_id in present:
        record = ledger["mines"][mine_id]
        lines.append(
            f"| [`{mine_id}`](scripts/mines/{mine_id}.py) | {record['problem_id']} | "
            f"{record['scope']} | `{record['certificate_sha256'][:12]}` |"
        )
    lines += ["", "## Tables", ""]
    for mine_id in present: 
        record = ledger["mines"][mine_id]
        lines += [
            f"### {record['problem_id']} · {record['title']}", "",
            record["scope"], "",
            f"**Frontier.** {record['frontier']}", "",
            "```json",
            json.dumps(record["summary"], indent=2, sort_keys=True, ensure_ascii=False),
            "```", "",
            f"Run `python3 scripts/mine.py --mine {mine_id}`.", "",
        ]
    lines.append("The JSON above is the checked summary. The ledger stores it and the certificate hash.")
    lines.append("")
    return "\n".join(lines)


def snapshot():
    return load_ledger()


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--mine", action="append", choices=list(mines.MINES))
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--list", action="store_true")
    opts = parser.parse_args(argv)
    try:
        if opts.list:
            for module in mines.all_mines():
                item = module.MINE
                print(f"{item['id']:20s} {item['problem_id']}  {item['title']}")
            return 0
        ledger = load_ledger()
        selected = opts.mine or list(mines.MINES)
        for mine_id in selected:
            module = mines.load(mine_id)
            record, search_s, check_s = run_mine(module)
            flag = "HOLDS" if record["holds"] else "CHECK THIS"
            print(f"{mine_id:20s} {record['problem_id']} {flag:10s} "
                  f"search {search_s:5.2f}s  check {check_s:5.2f}s  {record['certificate_sha256'][:12]}")
            if not record["holds"]:
                raise MineError(3, f"{mine_id} did not hold inside a range that should be known mathematics")
            stored = json.loads(json.dumps(record))
            if opts.check:
                if ledger["mines"].get(mine_id) != stored:
                    raise MineError(1, f"Stale mine ledger for {mine_id}: run python3 scripts/mine.py")
            else:
                ledger["mines"][mine_id] = stored
        report = render(ledger)
        if opts.check:
            if not REPORT.exists() or REPORT.read_text(encoding="utf-8") != report:
                raise MineError(1, "Stale MINES.md: run python3 scripts/mine.py")
            print(f"OK: {len(selected)} mine(s) reproduced the committed ledger")
        else:
            RESULTS.write_text(dump(ledger), encoding="utf-8")
            REPORT.write_text(report, encoding="utf-8")
            print("Updated data/mine_results.json and MINES.md")
        return 0
    except MineError as exc:
        print(exc, file=sys.stderr)
        return exc.code


if __name__ == "__main__":
    sys.exit(main())
