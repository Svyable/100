#!/usr/bin/env python3
"""Exact fixed-first-denominator gate for the M019 Erdős–Straus campaign.

For c>0 with n+c divisible by 4, x=(n+c)//4, m=n*x:
    4/n = 1/x + 1/y + 1/z
iff (c*y-m)*(c*z-m)=m*m with both factors positive.
No floating point, search cutoff, or external package is used.
"""
import argparse
from fractions import Fraction
from math import isqrt


def factor(n):
    if n < 1:
        raise ValueError("positive integer required")
    out = {}
    p = 2
    while p * p <= n:
        if n % p == 0:
            e = 0
            while n % p == 0:
                n //= p
                e += 1
            out[p] = e
        p = 3 if p == 2 else p + 2
    if n > 1:
        out[n] = out.get(n, 0) + 1
    return out


def divisors_from_factors(factors):
    divs = [1]
    for p, exponent in factors.items():
        divs = [d * p**j for d in divs for j in range(exponent + 1)]
    return sorted(divs)


def witness(n, c):
    """Return (x,y,z,d) or None. Enumerates *all* divisors of m² exactly."""
    if n <= 1 or c <= 0 or (n + c) % 4:
        raise ValueError("require n>1, c>0, 4|(n+c)")
    x = (n + c) // 4
    m = n * x
    squared = {p: 2 * e for p, e in factor(m).items()}
    for d in divisors_from_factors(squared):
        e = m * m // d
        if (m + d) % c == 0 and (m + e) % c == 0:
            y, z = (m + d) // c, (m + e) // c
            assert Fraction(4, n) == Fraction(1, x) + Fraction(1, y) + Fraction(1, z)
            return (x, y, z, d)
    return None


def subgroup_residues(n, c):
    """Independent modular certificate: residues generated by prime factors of m."""
    x = (n + c) // 4
    m = n * x
    if m % c == 0:
        raise ValueError("this modular gate requires gcd(m,c)=1")
    from math import gcd
    if gcd(m, c) != 1:
        raise ValueError("this modular gate requires gcd(m,c)=1")
    residues = {1}
    for p in factor(m):
        residues = {a * pow(p, j, c) % c
                    for a in residues for j in range(c)}
    return m % c, residues


def prime(n):
    return n >= 2 and all(n % d for d in range(2, isqrt(n) + 1))


def check():
    assert prime(1129) and 1129 % 24 == 1
    assert factor(1129) == {1129: 1}
    assert factor(283) == {283: 1}
    assert factor(284) == {2: 2, 71: 1}
    for c, expected in [(3, {1}), (7, {1, 2, 4})]:
        mres, group = subgroup_residues(1129, c)
        assert mres == 1 and group == expected
        assert (-mres) % c not in group
        assert witness(1129, c) is None
    assert witness(1129, 11)[:3] == (285, 29260, 99103620)
    assert witness(97, 3) is not None
    assert witness(73, 7) is not None
    for n in range(25, 1129):
        if n % 24 == 1 and prime(n):
            assert witness(n, 3) is not None or witness(n, 7) is not None
    print("PASS: 1129 is prime and the first prime n=1 mod 24 <=1129")
    print("      for which both fixed shifts c=3 and c=7 fail.")
    print("      Independent subgroup and exhaustive-divisor checks agree.")
    print("      c=11 positive control:", witness(1129, 11)[:3])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    check()
