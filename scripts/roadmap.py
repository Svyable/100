#!/usr/bin/env python3
"""Validate data/roadmap.json, compute live metrics and render ROADMAP.md.

Metric values are computed from the registry, lab, research program, claim
ledger and Solved archive, so the roadmap cannot drift from the evidence.
"""
import argparse
import json
from rank import ROOT
import research
import lab

SOURCE = ROOT / "data" / "roadmap.json"
CLAIMS = ROOT / "data" / "claim_reviews_2026.json"
OUTPUT = ROOT / "ROADMAP.md"
HORIZONS = ("shipped", "now", "next", "later")


class RoadmapError(ValueError):
    pass


def metric_values():
    items, program, solved = research.load()
    covered = lab.coverage(items, program)
    computable = [p for p in items if p["modality"] in lab.COMPUTABLE]
    claims = json.loads(CLAIMS.read_text(encoding="utf-8"))["reviews"]
    active = {p["id"] for p in items}
    return {
        "verifier_coverage": len(covered),
        "computable_coverage": sum(p["id"] in covered for p in computable),
        "engines": len(lab.probes.ENGINES),
        "campaigns": sum(c["problem_id"] in active for c in program["campaigns"]),
        "claims_triaged": len(claims),
        "restricted_verified": sum(m["classification"] == "restricted_verified"
                                   for m in program["milestones"]),
        "solved": len(solved),
    }


def load():
    doc = json.loads(SOURCE.read_text(encoding="utf-8"))
    items, _, _ = research.load()
    ids = {p["id"] for p in items}
    if tuple(doc["horizons"]) != HORIZONS:
        raise RoadmapError(f"horizons must be exactly {HORIZONS}")
    tracks = {t["id"] for t in doc["tracks"]}
    values = metric_values()
    for m in doc["metrics"]:
        if m["id"] not in values:
            raise RoadmapError(f"metric {m['id']} has no live computation")
        m["value"] = values[m["id"]]
    seen = set()
    for it in doc["items"]:
        where = f"roadmap item {it.get('id')}"
        for key in ("id", "track", "horizon", "title", "outcome", "evidence"):
            if not isinstance(it.get(key), str) or not it[key].strip():
                raise RoadmapError(f"{where}: missing {key}")
        if it["id"] in seen:
            raise RoadmapError(f"{where}: duplicate id")
        seen.add(it["id"])
        if it["track"] not in tracks:
            raise RoadmapError(f"{where}: unknown track {it['track']}")
        if it["horizon"] not in HORIZONS:
            raise RoadmapError(f"{where}: unknown horizon {it['horizon']}")
        if it["horizon"] in ("now", "next") and not it.get("exit"):
            raise RoadmapError(f"{where}: now/next items need exit criteria")
        if not (ROOT / it["evidence"]).exists():
            raise RoadmapError(f"{where}: evidence path {it['evidence']} does not exist")
        bad = [p for p in it["problems"] if p not in ids]
        if bad:
            raise RoadmapError(f"{where}: unknown problems {bad}")
    import approach
    try:
        approach.assert_roadmap(doc)
    except approach.ApproachError as exc:
        raise RoadmapError(str(exc)) from exc
    return doc


def snapshot():
    doc = load()
    counts = {h: sum(i["horizon"] == h for i in doc["items"]) for h in HORIZONS}
    return {**doc, "counts": counts}


def _cell(text):
    return str(text).replace("|", "\\|")


def render():
    doc = snapshot()
    names = {p["id"]: p["name"] for p in research.load()[0]}
    track = {t["id"]: t["name"] for t in doc["tracks"]}
    lines = [
        "# Roadmap — 100 mathematical grand challenges", "",
        f"Generated by `python3 scripts/roadmap.py` from [data/roadmap.json](data/roadmap.json); "
        f"do not edit by hand. As of **{doc['as_of']}**. Also on the "
        "[public dashboard](https://svyable.github.io/100/#roadmap).", "",
        f"**Mission.** {doc['mission']}", "",
        f"> {doc['interpretation']}", "",
        "## Scoreboard", "",
        "Current values are computed from the repository on every build, not typed in.", "",
        "| Metric | Start | Now | Target |", "|---|---:|---:|---:|",
    ]
    for m in doc["metrics"]:
        target = "—" if m["target"] is None else m["target"]
        lines.append(f"| {m['label']} ({m['unit']}) | {m['baseline']} | **{m['value']}** | {target} |")
    lines += ["", "Solved has no target on purpose: it grows only through the promotion gate in "
              "[docs/RESEARCH_ENGINE.md](docs/RESEARCH_ENGINE.md).", "",
              "## Tracks", "", "| Track | Goal | Shipped | Now | Next | Later |",
              "|---|---|---:|---:|---:|---:|"]
    for t in doc["tracks"]:
        c = [sum(i["track"] == t["id"] and i["horizon"] == h for i in doc["items"]) for h in HORIZONS]
        lines.append(f"| {t['name']} | {_cell(t['goal'])} | " + " | ".join(map(str, c)) + " |")
    titles = {"shipped": "Shipped", "now": "Now", "next": "Next", "later": "Later"}
    for h in HORIZONS:
        lines += ["", f"## {titles[h]} ({doc['counts'][h]})", "", f"_{doc['horizons'][h]}_", ""]
        for it in (i for i in doc["items"] if i["horizon"] == h):
            box = "x" if h == "shipped" else " "
            probs = ", ".join(f"{p} {names[p]}" for p in it["problems"][:4])
            if len(it["problems"]) > 4:
                probs += f" +{len(it['problems']) - 4} more"
            lines.append(f"- [{box}] **{it['id']} · {it['title']}** ({track[it['track']]}) — "
                         f"{it['outcome']} [Evidence]({it['evidence']})")
            if it.get("exit"):
                lines.append(f"  - Done when: {it['exit']}")
            if probs:
                lines.append(f"  - Problems: {probs}")
    lines += ["", "## Updating", "",
              "Edit [data/roadmap.json](data/roadmap.json) in the same PR that ships the work, "
              "move the item to `shipped`, then run `python3 scripts/roadmap.py` and "
              "`python3 scripts/build_site.py`. CI fails if either output is stale, if an "
              "evidence path is missing, or if a now/next item lacks exit criteria.", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if ROADMAP.md is stale")
    opts = parser.parse_args()
    text = render()
    if opts.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit("Stale ROADMAP.md: run python3 scripts/roadmap.py")
        print("OK: roadmap validated and ROADMAP.md current")
    else:
        OUTPUT.write_text(text, encoding="utf-8")
        print("Updated ROADMAP.md")


if __name__ == "__main__":
    main()
