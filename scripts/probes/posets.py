"""M079 - The 1/3-2/3 conjecture on every poset with at most N elements.

Search: posets are generated by adding a new maximal element above an order
ideal of a smaller poset, canonicalised under an invariant-refined labelling.
Linear extensions are counted by a down-set DP over maximal elements.
Check: completeness by the orbit-counting identity sum n!/|Aut(P)| = number of
labelled posets (OEIS A001035), automorphisms recomputed directly, and every
balance witness recounted with an independent DP over minimal elements.
"""
from fractions import Fraction
from itertools import permutations, product
from math import factorial

from .core import digest, fraction_text, require

PROBE = {
    "id": "one_third",
    "problem_id": "M079",
    "title": "Balanced pairs (1/3-2/3 conjecture) for every poset up to N elements",
    "engines": ["poset_census"],
    "frontier": ("Known: verified for all posets with at most 11 elements (Peczarski) and for "
                 "width-2 posets (Linial 1984); best general bound ~0.276 (Brightwell-Felsner-Trotter)."),
    "levels": {"smoke": {"max_n": 6}, "deep": {"max_n": 7}},
}

KNOWN_UNLABELLED = {1: 1, 2: 2, 3: 5, 4: 16, 5: 63, 6: 318, 7: 2045}            # OEIS A000112
KNOWN_LABELLED = {1: 1, 2: 3, 3: 19, 4: 219, 5: 4231, 6: 130023, 7: 6129859}   # OEIS A001035


def scope(params):
    return (f"Every non-chain poset with 2..{params['max_n']} elements has an incomparable pair x, y "
            "with 1/3 <= Pr[x < y] <= 2/3 over uniformly random linear extensions.")


# A poset on n elements is a tuple below[v] = bitmask of elements strictly below v.

def _relabel(below, order):
    pos = {v: i for i, v in enumerate(order)}
    out = [0] * len(below)
    for v, m in enumerate(below):
        out[pos[v]] = sum(1 << pos[u] for u in range(len(below)) if m >> u & 1)
    return tuple(out)


def _classes(below):
    n = len(below)
    above = [sum(1 << u for u in range(n) if below[u] >> v & 1) for v in range(n)]
    key = [(bin(below[v]).count("1"), bin(above[v]).count("1")) for v in range(n)]
    groups = {}
    for v in range(n):
        groups.setdefault(key[v], []).append(v)
    return [groups[k] for k in sorted(groups)]


def canonical(below):
    best = None
    for parts in product(*(permutations(c) for c in _classes(below))):
        image = _relabel(below, [v for p in parts for v in p])
        if best is None or image > best:
            best = image
    return best


def _ideals(below):
    n = len(below)
    return [m for m in range(1 << n) if all(below[v] & ~m == 0 for v in range(n) if m >> v & 1)]


def census(n):
    level = {()}
    for _ in range(n):
        level = {canonical(P + (I,)) for P in level for I in _ideals(P)}
    return sorted(level)


def extensions_above(below):
    """Number of linear extensions: f(S) sums f(S - v) over maximal v of each down-set S."""
    n = len(below)
    f = {0: 1}
    for S in range(1, 1 << n):
        if any(S >> v & 1 and below[v] & ~S for v in range(n)):
            continue  # not a down-set
        f[S] = sum(f[S & ~(1 << v)] for v in range(n)
                   if S >> v & 1 and not any(S >> u & 1 and below[u] >> v & 1 for u in range(n)))
    return f[(1 << n) - 1]


def _with(below, x, y):
    """Add x < y and take the transitive closure."""
    n = len(below)
    b = list(below)
    b[y] |= 1 << x | b[x]
    changed = True
    while changed:
        changed = False
        for v in range(n):
            new = b[v]
            for u in range(n):
                if b[v] >> u & 1:
                    new |= b[u]
            if new != b[v]:
                b[v], changed = new, True
    return tuple(b)


def best_pair(below):
    n = len(below)
    e = extensions_above(below)
    best = None
    for x in range(n):
        for y in range(x + 1, n):
            if below[y] >> x & 1 or below[x] >> y & 1:
                continue
            a = extensions_above(_with(below, x, y))
            bal = min(Fraction(a, e), 1 - Fraction(a, e))
            if best is None or bal > best[0]:
                best = (bal, x, y, a, e)
    return best


def search(params):
    out, holds, worst = {}, True, None
    for n in range(1, params["max_n"] + 1):
        rows = []
        for P in census(n):
            bp = best_pair(P)
            if bp is None:
                rows.append({"poset": list(P), "chain": True})
                continue
            bal, x, y, a, e = bp
            if bal < Fraction(1, 3):
                holds = False
            if worst is None or bal < worst:
                worst = bal
            rows.append({"poset": list(P), "pair": [x, y], "x_before_y": a, "extensions": e})
        out[str(n)] = rows
    return {
        "holds": holds,
        "summary": {"posets": {n: len(r) for n, r in out.items()},
                    "least_best_balance": fraction_text(worst),
                    "certificate_sha256": digest(out)},
        "certificate": out,
    }


def _count_by_minimal(below):
    """Independent count: repeatedly remove a minimal element (memoised on remaining set)."""
    n = len(below)
    memo = {}
    def go(rest):
        if rest == 0:
            return 1
        if rest in memo:
            return memo[rest]
        total = sum(go(rest & ~(1 << v)) for v in range(n)
                    if rest >> v & 1 and below[v] & rest == 0)
        memo[rest] = total
        return total
    return go((1 << n) - 1)


def _form(below):
    """Independent canonical form: least sorted relation list over invariant-ordered relabellings."""
    n = len(below)
    rel = [(u, v) for v in range(n) for u in range(n) if below[v] >> u & 1]
    key = [(sum(1 for u, w in rel if w == v), sum(1 for u, w in rel if u == v)) for v in range(n)]
    blocks = [[v for v in range(n) if key[v] == k] for k in sorted(set(key))]
    best = None
    for images in product(*(permutations(b) for b in blocks)):
        order = [v for img in images for v in img]
        pos = {v: i for i, v in enumerate(order)}
        image = tuple(sorted((pos[u], pos[v]) for u, v in rel))
        if best is None or image < best:
            best = image
    return best


def _automorphisms(below):
    """|Aut(P)|: automorphisms preserve (#below, #above), so only those relabellings are tried."""
    n = len(below)
    rel = {(u, v) for v in range(n) for u in range(n) if below[v] >> u & 1}
    down = [sum(1 for u in range(n) if (u, v) in rel) for v in range(n)]
    up = [sum(1 for w in range(n) if (v, w) in rel) for v in range(n)]
    groups = {}
    for v in range(n):
        groups.setdefault((down[v], up[v]), []).append(v)
    blocks = list(groups.values())
    count = 0
    for images in product(*(permutations(b) for b in blocks)):
        p = {}
        for b, img in zip(blocks, images):
            p.update(zip(b, img))
        if all((p[u], p[v]) in rel for u, v in rel):
            count += 1
    return count


def check(params, result):
    cert = result["certificate"]
    worst = None
    for n in range(1, params["max_n"] + 1):
        rows = cert[str(n)]
        require(len(rows) == KNOWN_UNLABELLED[n], f"n={n}: wrong number of posets")
        labelled = Fraction(0)
        for r in rows:
            below = tuple(r["poset"])
            require(all(not below[v] >> v & 1 for v in range(n)), "poset must be irreflexive")
            require(all(below[u] & ~below[v] == 0 for v in range(n) for u in range(n)
                        if below[v] >> u & 1), "poset must be transitive")
            labelled += Fraction(factorial(n), _automorphisms(below))
            if r.get("chain"):
                require(all((below[u] >> v & 1) or (below[v] >> u & 1)
                            for u in range(n) for v in range(u + 1, n)), "claimed chain is not total")
                continue
            x, y = r["pair"]
            require(not below[y] >> x & 1 and not below[x] >> y & 1, "witness pair is comparable")
            e = _count_by_minimal(below)
            ext = list(below)
            ext[y] |= 1 << x
            for _ in range(n):  # transitive closure by repeated OR-propagation
                nxt = []
                for m in ext:
                    for u in range(n):
                        if m >> u & 1:
                            m |= ext[u]
                    nxt.append(m)
                ext = nxt
            a = _count_by_minimal(tuple(ext))
            require((a, e) == (r["x_before_y"], r["extensions"]), f"n={n}: extension count mismatch")
            bal = min(Fraction(a, e), 1 - Fraction(a, e))
            require(bal >= Fraction(1, 3), f"n={n}: witness pair is not balanced")
            worst = bal if worst is None or bal < worst else worst
        require(len({_form(tuple(r["poset"])) for r in rows}) == len(rows),
                f"n={n}: listed posets are not pairwise non-isomorphic")
        # sum of n!/|Aut| equals the labelled count only if the list is complete and
        # pairwise non-isomorphic (given its length matches the unlabelled count).
        require(labelled == KNOWN_LABELLED[n], f"n={n}: orbit-counting identity fails")
    require(fraction_text(worst) == result["summary"]["least_best_balance"], "summary mismatch")
    require(result["summary"]["certificate_sha256"] == digest(cert), "certificate hash mismatch")
